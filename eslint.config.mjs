import nextTs from "eslint-config-next/typescript";

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  {
    // An underscore-prefixed argument is the conventional way to say
    // "this parameter exists because the signature requires it, and is
    // deliberately unused" — which is exactly the shape of the Solv
    // stubs, whose whole job is to throw until the integration is real.
    // Without this the only way to silence it is to delete the name, and
    // a nameless parameter documents nothing.
    rules: {
      "@typescript-eslint/no-unused-vars": [
        "warn",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_", caughtErrorsIgnorePattern: "^_" },
      ],
    },
  },
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
  ]),
]);

export default eslintConfig;
